import React from 'react';
import {
  TableRow,
  TableCell,
  IconButton,
  Tooltip,
  LinearProgress,
  Typography,
  Box,
} from '@mui/material';
import FilterAltOutlinedIcon from '@mui/icons-material/FilterAltOutlined';
import WarningAmberIcon from '@mui/icons-material/WarningAmber';
import { useTranslation } from 'react-i18next';
import { InstrumentScoreRow } from '../../utils/instrumentScore';
import { NumberFormatOption } from '../../types/preferences';
import { formatPercent, formatSignedPnl, formatDurationMs } from '../../lib/formatters';
import { Sparkline } from './Sparkline';
import { InstrumentRatingBadge } from './InstrumentRatingBadge';
import { getRowSx, styles } from './InstrumentRow.styles';

export interface Props {
  row: InstrumentScoreRow;
  currency: string;
  numberFormat: NumberFormatOption;
  isSelected: boolean;
  onSelect: (symbol: string) => void;
}

export const InstrumentRow: React.FC<Props> = React.memo(
  ({ row, currency, numberFormat, isSelected, onSelect }) => {
    const { t, i18n } = useTranslation();
    const currentLang = i18n.language || 'en-US';

    const pnlData = formatSignedPnl(row.netPnl, currency, numberFormat, currentLang);
    const avgData = formatSignedPnl(row.avgPnl, currency, numberFormat, currentLang);
    const formattedDuration = formatDurationMs(row.avgDurationMs, currentLang);

    const handleKeyDown = (e: React.KeyboardEvent) => {
      if (e.key === 'Enter' || e.key === ' ') {
        e.preventDefault();
        onSelect(row.symbol);
      }
    };

    // Progress bar color based on rating
    const getProgressBarColor = (theme: any) => {
      if (row.rating === 'best' || row.rating === 'good') {
        return theme.palette.trade.gain;
      }
      if (row.rating === 'worst' || row.rating === 'weak') {
        return theme.palette.trade.loss;
      }
      return theme.palette.trade.breakeven;
    };

    // Score tooltip content
    const tooltipTitle = (
      <Box sx={{ p: 0.5, maxWidth: 320 }}>
        <Typography variant="caption" sx={{ fontWeight: 700, display: 'block', mb: 0.5 }}>
          {t('instruments.scoreBreakdownHeader', { defaultValue: 'Score Breakdown' })} (
          {row.score !== null ? row.score : '-'})
        </Typography>
        <Typography variant="caption" color="text.secondary" sx={{ display: 'block', mb: 1 }}>
          {t('instruments.scoreTooltipConfidence', {
            defaultValue: 'Confidence {{confidence}}% (n={{trades}})',
            confidence: Math.round(row.scoreConfidence * 100),
            trades: row.trades,
          })}
        </Typography>

        {row.warnings && row.warnings.includes('fragileEdge') && (
          <Box
            sx={{
              display: 'flex',
              alignItems: 'center',
              gap: 0.5,
              mb: 1,
              color: 'warning.main',
              bgcolor: 'action.hover',
              p: 0.5,
              borderRadius: 1,
            }}
          >
            <WarningAmberIcon sx={{ fontSize: 16 }} />
            <Typography variant="caption" sx={{ fontWeight: 600 }}>
              {t('instruments.scoreTooltipFragileEdge', {
                defaultValue: 'Fragile edge: over 60% of profits generated by top trade(s)',
              })}
            </Typography>
          </Box>
        )}

        {row.breakdown && row.breakdown.length > 0 && (
          <table style={{ width: '100%', fontSize: '0.72rem', borderCollapse: 'collapse' }}>
            <thead>
              <tr style={{ borderBottom: '1px solid rgba(255,255,255,0.15)', textAlign: 'left' }}>
                <th style={{ paddingBottom: 2 }}>
                  {t('instruments.metricValue', { defaultValue: 'Metric' })}
                </th>
                <th style={{ textAlign: 'right', paddingBottom: 2 }}>
                  {t('instruments.metricPercentile', { defaultValue: 'Pct' })}
                </th>
                <th style={{ textAlign: 'right', paddingBottom: 2 }}>
                  {t('instruments.metricWeight', { defaultValue: 'W' })}
                </th>
                <th style={{ textAlign: 'right', paddingBottom: 2 }}>
                  {t('instruments.metricContribution', { defaultValue: 'Score' })}
                </th>
              </tr>
            </thead>
            <tbody>
              {row.breakdown.map((item) => {
                const metricLabels: Record<string, string> = {
                  expectancy: t('instruments.metricExpectancy', { defaultValue: 'Expectancy' }),
                  profitFactor: t('instruments.metricProfitFactor', {
                    defaultValue: 'Profit factor',
                  }),
                  sortino: t('instruments.metricSortino', { defaultValue: 'Sortino' }),
                  maxDrawdown: t('instruments.metricMaxDrawdown', { defaultValue: 'Max DD (inv)' }),
                  recoveryFactor: t('instruments.metricRecoveryFactor', {
                    defaultValue: 'Recovery',
                  }),
                  payoffRatio: t('instruments.metricPayoffRatio', { defaultValue: 'Payoff' }),
                  winRate: t('instruments.metricWinRate', { defaultValue: 'Win rate' }),
                  consistency: t('instruments.metricConsistency', { defaultValue: 'Consistency' }),
                };
                return (
                  <tr key={item.key}>
                    <td style={{ padding: '2px 0' }}>{metricLabels[item.key] || item.key}</td>
                    <td style={{ textAlign: 'right', fontFamily: 'monospace' }}>
                      {Math.round(item.percentile)}%
                    </td>
                    <td style={{ textAlign: 'right', fontFamily: 'monospace' }}>{item.weight}</td>
                    <td style={{ textAlign: 'right', fontFamily: 'monospace', fontWeight: 600 }}>
                      {Math.round(item.contribution * 10) / 10}
                    </td>
                  </tr>
                );
              })}
            </tbody>
          </table>
        )}
      </Box>
    );

    return (
      <TableRow
        hover
        tabIndex={0}
        role="button"
        aria-selected={isSelected}
        onClick={() => onSelect(row.symbol)}
        onKeyDown={handleKeyDown}
        sx={getRowSx(isSelected)}
      >
        {/* Symbol + Rating Badge */}
        <TableCell sx={styles.symbolCell}>
          <div style={{ display: 'inline-flex', alignItems: 'center', gap: 6 }}>
            <span>{row.symbol}</span>
            <InstrumentRatingBadge rating={row.rating} />
          </div>
        </TableCell>

        {/* Trades */}
        <TableCell align="right">{row.trades}</TableCell>

        {/* Win % */}
        <TableCell
          align="right"
          sx={{
            fontWeight: 600,
            color: (theme) =>
              row.winRate >= 60
                ? theme.palette.trade.gain
                : row.winRate < 45
                  ? theme.palette.trade.loss
                  : 'text.primary',
          }}
        >
          {formatPercent(row.winRate, 0, numberFormat, currentLang)}
        </TableCell>

        {/* Net P&L */}
        <TableCell
          align="right"
          sx={{
            fontWeight: 700,
            fontFamily: "'JetBrains Mono', monospace",
            color: (theme) =>
              pnlData.isPositive
                ? theme.palette.trade.gain
                : pnlData.isNegative
                  ? theme.palette.trade.loss
                  : theme.palette.trade.breakeven,
          }}
        >
          {pnlData.text}
        </TableCell>

        {/* Score Column */}
        <TableCell align="right" sx={styles.scoreCell}>
          <Tooltip title={tooltipTitle} arrow enterTouchDelay={0}>
            <div
              tabIndex={0}
              role="region"
              aria-label={`Score: ${row.score !== null ? row.score : 'N/A'}, Rating: ${row.rating}`}
              style={{
                display: 'inline-flex',
                flexDirection: 'column',
                alignItems: 'flex-end',
                width: 70,
                cursor: 'pointer',
                outline: 'none',
              }}
            >
              <Typography
                variant="body2"
                sx={{
                  fontFamily: "'JetBrains Mono', monospace",
                  fontWeight: 700,
                  fontSize: '0.82rem',
                }}
              >
                {row.score !== null ? row.score : '-'}
              </Typography>
              {row.score !== null && (
                <LinearProgress
                  variant="determinate"
                  value={row.score}
                  sx={{
                    width: '100%',
                    height: 4,
                    borderRadius: 2,
                    mt: 0.25,
                    bgcolor: 'action.hover',
                    '& .MuiLinearProgress-bar': {
                      bgcolor: getProgressBarColor,
                    },
                  }}
                />
              )}
            </div>
          </Tooltip>
        </TableCell>

        {/* Avg P&L */}
        <TableCell
          align="right"
          sx={{
            fontFamily: "'JetBrains Mono', monospace",
            color: (theme) =>
              avgData.isPositive
                ? theme.palette.trade.gain
                : avgData.isNegative
                  ? theme.palette.trade.loss
                  : 'text.secondary',
          }}
        >
          {avgData.text}
        </TableCell>

        {/* Avg Duration */}
        <TableCell align="right" sx={{ color: 'text.secondary', ...styles.durationCell }}>
          {formattedDuration}
        </TableCell>

        {/* Share % */}
        <TableCell align="right" sx={{ color: 'text.secondary', ...styles.shareCell }}>
          {formatPercent(row.sharePercent, 1, numberFormat, currentLang)}
        </TableCell>

        {/* Trend Sparkline */}
        <TableCell align="center" sx={{ py: 0.5 }}>
          <Sparkline points={row.sparkline} isPositive={row.netPnl >= 0} />
        </TableCell>

        {/* Action */}
        <TableCell align="right" sx={{ py: 0.5 }}>
          <Tooltip title={t('instruments.details', { defaultValue: 'Деталі' })}>
            <IconButton
              size="small"
              color={isSelected ? 'primary' : 'default'}
              onClick={(e) => {
                e.stopPropagation();
                onSelect(row.symbol);
              }}
              aria-label={t('instruments.details', { defaultValue: 'Деталі' })}
              sx={{
                p: 0.5,
                bgcolor: isSelected ? 'action.selected' : 'transparent',
              }}
            >
              <FilterAltOutlinedIcon
                fontSize="small"
                className="instrument-filter-icon"
                sx={{
                  transition: 'transform 0.2s cubic-bezier(0.4, 0, 0.2, 1), color 0.2s ease',
                }}
              />
            </IconButton>
          </Tooltip>
        </TableCell>
      </TableRow>
    );
  }
);

InstrumentRow.displayName = 'InstrumentRow';
